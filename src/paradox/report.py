# Long tables must break across pages (pandoc wraps them in non-breakable figures) and stay unhyphenated.
_TYPST_HEADER = "#show figure: set block(breakable: true)\n#show table: set text(size: 7.5pt, hyphenate: false)"
_RULE_STYLE = {"SINGLE": ("#222222", "o"), "MV": ("#1b6ca8", "s"), "CW": ("#2a9d8f", "^"), "SEQ": ("#c0392b", "v"), "DELIB": ("#8e6c8a", "D")}


def _f(x, nd=4) -> str:
    return "" if x is None else f"{x:.{nd}f}"


def _banner(doc: dict) -> str:
    if doc["label"] == "exploratory":
        return ("> **EXPLORATORY. Not a finding.** This report comes from an exploratory run made before the owner froze the "
                "protocol. It does not test any preregistered hypothesis and must not be cited as a result.\n")
    return "> Confirmatory run under a frozen protocol.\n"


def _header(doc: dict, title: str) -> list[str]:
    return [
        "<!-- SPDX-License-Identifier: LicenseRef-PARADOX-NC-Research-1.0 -->",
        f"# {title}",
        "",
        _banner(doc),
        f"- Experiment id: `{doc['experiment_id']}`; label: **{doc['label']}**; kind: `{doc['kind']}`",
        f"- Result schema: {doc['schema_version']}; config SHA-256: `{doc['config_sha256']}`",
        f"- Code revision: `{doc['code_revision']}`; created (UTC): {doc['created_utc']}",
        f"- Seeds ({len(doc['seeds'])}): {', '.join(str(s) for s in doc['seeds'])}",
        f"- Claims boundary: {doc['claims_boundary']}",
        "",
        "Every number below is generated by `paradox report` from `results.json` in this folder; none is typed by hand.",
        "",
    ]


def _aggregation(doc: dict, out: Path, figs: Path) -> list[str]:
    cfg, summ = doc["config"], doc["summary"]
    lines = ["## Run records", ""]
    n_ex = sum(r["excluded"] for r in doc["records"])
    lines += [f"{len(doc['records'])} runs ({cfg['n_items']} items each); {n_ex} excluded by invariant checks.", ""]
    for r in doc["records"]:
        if r["excluded"]:
            lines.append(f"- {r['record_id']} excluded: {r['exclusion_reason']}")
    lines += ["", "## Accuracy and paired difference from SINGLE", "",
              "Delta is the mean per-item paired difference in correctness against SINGLE (reasoner 1, one call) of the same run. "
              "SD is the between-seed standard deviation of the per-run Delta; the interval is the seed-level t 95% interval. "
              "`theory` is the closed-form MV accuracy (odd budgets only).", ""]
    lines += ["| Scenario | lambda | Rule | Calls | Accuracy | theory | Delta | SD(Delta) | t95 low | t95 high | seeds |",
              "|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in summ:
        lines.append(f"| {s['scenario']} | {s['lambda']:g} | {s['rule']} | {s['budget']} | {_f(s['accuracy_mean'])} | "
                     f"{_f(s.get('accuracy_theory'))} | {_f(s['delta_vs_single_mean'])} | {_f(s.get('delta_sd'))} | "
                     f"{_f(s.get('delta_t95_low'))} | {_f(s.get('delta_t95_high'))} | {s['n_seeds']} |")
    lines += ["", "## Secondary metrics (means over seeds)", "",
              "| Scenario | lambda | Rule | Calls | Brier | ECE | Non-unanimous share |", "|---|---|---|---|---|---|---|"]
    for s in summ:
        lines.append(f"| {s['scenario']} | {s['lambda']:g} | {s['rule']} | {s['budget']} | {_f(s['brier_mean'])} | "
                     f"{_f(s['ece_mean'])} | {_f(s['disagreement_share_mean'])} |")
    sds = [s["delta_sd"] for s in summ if "delta_sd" in s and s["rule"] != "SINGLE"]
    if sds:
        lines += ["", "## Between-seed spread", "",
                  f"Across {len(sds)} non-baseline cells, SD(Delta) ranges from {min(sds):.4f} to {max(sds):.4f} "
                  f"(median {sorted(sds)[len(sds) // 2]:.4f}).", ""]
    cells = sorted({(s["scenario"], s["lambda"]) for s in summ})
    ncol = min(2, len(cells))
    nrow = -(-len(cells) // ncol)
    fig, axes = plt.subplots(nrow, ncol, figsize=(3.6 * ncol, 3.0 * nrow), squeeze=False, sharey=True)
    flat = list(axes.flat)
    for ax in flat[len(cells):]:
        ax.set_visible(False)
    for ax, (sid, lam) in zip(flat, cells):
        for rule in ("MV", "CW", "SEQ", "DELIB"):
            pts = sorted((s["budget"], s["accuracy_mean"], min(s["accuracy_per_seed"]), max(s["accuracy_per_seed"]))
                         for s in summ if s["scenario"] == sid and s["lambda"] == lam and s["rule"] == rule)
            if not pts:
                continue
            col, mk = _RULE_STYLE[rule]
            xs, ys, lo, hi = zip(*pts)
            ax.plot(xs, ys, marker=mk, color=col, label=rule, lw=1.2, ms=4)
            ax.fill_between(xs, lo, hi, color=col, alpha=0.12, lw=0)
        base = [s["accuracy_mean"] for s in summ if s["scenario"] == sid and s["lambda"] == lam and s["rule"] == "SINGLE"]
        if base:
            ax.axhline(base[0], color="#222222", ls="--", lw=1, label="SINGLE")
        ax.set_xscale("log", base=2)
        ax.set_title(f"{sid}, lambda = {lam:g}", fontsize=9)
        ax.set_xlabel("calls per item (log scale)", fontsize=8)
        ax.tick_params(labelsize=7)
    for row in axes:
        row[0].set_ylabel("accuracy (proportion correct)", fontsize=8)
    flat[0].legend(fontsize=7, frameon=False)
    fig.suptitle(f"{doc['experiment_id']} ({doc['label']}): accuracy against budget", fontsize=9)
    fig.tight_layout()
    fig.savefig(figs / "accuracy_vs_budget.png", dpi=150)
    plt.close(fig)
    lines += ["", "## Figure", "",
              f"![Accuracy against calls per item for each rule, one panel per scenario and lambda, from {doc['experiment_id']} "
              f"({doc['label']}). Lines are means over {len(doc['seeds'])} seeds; shaded bands span the minimum and maximum seed; "
              "the dashed line is SINGLE.](figures/accuracy_vs_budget.png)", "",
              f"*Figure 1. Accuracy (proportion of items correct) against calls per item (log2 axis). Mean over {len(doc['seeds'])} "
              f"seeds of {cfg['n_items']} items; bands show the seed range, not a confidence interval.*", ""]
    return lines


def _validation(doc: dict, out: Path, figs: Path) -> list[str]:
    lines = ["## Deterministic checks and overall verdict", "", "| Check | Expected | Got | Pass |", "|---|---|---|---|"]
    for s in doc["summary"]:
        if "expected" in s:
            lines.append(f"| {s['check']} | {s['expected']} | {s['got']:.10f} | {s['pass']} |")
    mc = [s for s in doc["summary"] if s["check"] == "monte_carlo_cells"][0]
    lines += ["", f"Monte Carlo cells run: {mc['n_cells']}; excluded (inadmissible): {mc['n_excluded']}; "
              f"failing the {mc['tolerance_se']} SE tolerance: {mc['n_fail']}; max |z| = {mc['max_abs_z']:.3f}.", ""]
    lines += ["## Cells", "", "| Cell | Model | Parameters | n | Simulated | Theory | z | Pass |", "|---|---|---|---|---|---|---|---|"]
    for r in doc["records"]:
        prm = ", ".join(f"{k}={v}" for k, v in r["params"].items())
        if r["excluded"]:
            lines.append(f"| {r['record_id']} | {r['model']} | {prm} | {r['n']} | excluded | {r['exclusion_reason']} | | |")
        else:
            lines.append(f"| {r['record_id']} | {r['model']} | {prm} | {r['n']} | {r['accuracy_sim']:.5f} | {r['accuracy_theory']:.5f} | {r['z']:.2f} | {r['pass']} |")
    zs = [r["z"] for r in doc["records"] if not r["excluded"]]
    fig, ax = plt.subplots(figsize=(5, 3))
    ax.hist(zs, bins=30, color="#1b6ca8")
    ax.axvline(-mc["tolerance_se"], color="#c0392b", ls="--", lw=1)
    ax.axvline(mc["tolerance_se"], color="#c0392b", ls="--", lw=1)
    ax.set_xlabel("z = (simulated - theory) / Monte Carlo SE", fontsize=8)
    ax.set_ylabel("cells", fontsize=8)
    ax.set_title(f"{doc['experiment_id']} ({doc['label']}): {len(zs)} cells", fontsize=9)
    fig.tight_layout()
    fig.savefig(figs / "z_histogram.png", dpi=150)
    plt.close(fig)
    lines += ["", f"![Histogram of standardised deviations between simulated and closed-form majority accuracy over {len(zs)} cells; "
              f"dashed lines mark the +/- {mc['tolerance_se']} SE tolerance.](figures/z_histogram.png)", "",
              "*Figure 1. Standardised deviation z per validation cell. Cells share seeds across n, so they are not independent.*", ""]
    return lines


def _dependence(doc: dict, out: Path, figs: Path) -> list[str]:
    lines = ["## Cells", "", "| Cell | Model | p | r | n | Delta theory | Delta MC mean |", "|---|---|---|---|---|---|---|"]
    for r in doc["records"]:
        if r["excluded"]:
            lines.append(f"| {r['record_id']} | {r['model']} | {r['p']} | {r['r']} | {r['n']} | {r['exclusion_reason']} | |")
        else:
            lines.append(f"| {r['record_id']} | {r['model']} | {r['p']} | {r['r']} | {r['n']} | {r['delta_theory']:.5f} | {r['delta_mc_mean']:.5f} |")
    lines += ["", "## Sign agreement (analytic)", "", "| p | r | n | Signs | Agree |", "|---|---|---|---|---|"]
    for s in doc["summary"]:
        lines.append(f"| {s['p']} | {s['r']} | {s['n']} | {s['analytic_signs']} | {s['signs_agree']} |")
    return lines + [""]


def build_report(results_dir: str | Path, *, pdf: bool = False, title: str | None = None) -> dict:
    """Build ``report.md`` (and optionally ``report.pdf``) next to ``results.json``."""
    d = Path(results_dir)
    doc = load_result(d / "results.json")
    figs = d / "figures"
    figs.mkdir(exist_ok=True)
    title = title or f"{doc['experiment_id']} {doc['kind']} report ({doc['label']})"
    body = {"aggregation": _aggregation, "validation": _validation, "dependence": _dependence}[doc["kind"]](doc, d, figs)
    text = "\n".join(_header(doc, title) + body).rstrip() + "\n"
    (d / "report.md").write_text(text, encoding="utf-8")
    result = {"report_md": str(d / "report.md"), "figures": sorted(str(p) for p in figs.iterdir())}
    if pdf:
        result["report_pdf"] = build_pdf(d / "report.md")
    return result


def build_pdf(md_path: str | Path, pandoc: str | None = None) -> str:
    """Markdown -> Typst (pandoc, mainfont Libertinus Serif) -> PDF (typst package)."""
    md = Path(md_path).resolve()
    pandoc = pandoc or os.environ.get("PARADOX_PANDOC") or shutil.which("pandoc") or DEFAULT_PANDOC
    if not Path(pandoc).is_file():
        raise FileNotFoundError(f"pandoc not found at {pandoc}; set PARADOX_PANDOC")
    typ = md.with_suffix(".typ")
    subprocess.run([pandoc, str(md), "-s", "-f", "gfm", "-V", "mainfont=Libertinus Serif", "-V", "papersize=a4",
                    "-V", "fontsize=10pt", "-V", f"header-includes={_TYPST_HEADER}", "-o", str(typ)], check=True, cwd=md.parent)
    import typst

    pdf = md.with_suffix(".pdf")
    typst.compile(str(typ), output=str(pdf), root=str(md.parent))
    typ.unlink()
    return str(pdf)
